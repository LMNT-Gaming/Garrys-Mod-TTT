-- LMNT Unit-Tests: Integration Manager (eigene Instanzen, ohne Einfluss auf den laufenden Server)
local T = LMNT.Test

local function found(evidenceCount, version)
	return function()
		local ev = {}
		for i = 1, evidenceCount do ev[i] = "Beleg " .. i end
		return true, ev, version
	end
end

T.Describe("Integrationen", function(t)
	t:It("nicht installiert blockiert den Start nicht", function(e)
		local m = LMNT.Integrations.New({ persist = false })
		m:Register("fehlt", { detect = function() return false, {} end })
		e:NoError(function() m:StartAll() end)
		e:Equal(m:GetStatus("fehlt").state, "NOT_INSTALLED")
	end)
	t:It("ein einzelnes Merkmal reicht nicht für eine Aktivierung", function(e)
		local m = LMNT.Integrations.New({ persist = false })
		m:Register("schwach", { detect = found(1) })
		m:StartAll()
		e:Equal(m:GetStatus("schwach").state, "DETECTED")
		e:True(m:GetStatus("schwach").weak)
	end)
	t:It("fehlende Pflicht-Schnittstelle = INCOMPATIBLE mit Grund", function(e)
		local m = LMNT.Integrations.New({ persist = false })
		m:Register("x", { detect = found(2), validate = function() return { { name = "foo", ok = false } } end })
		m:StartAll()
		local st = m:GetStatus("x")
		e:Equal(st.state, "INCOMPATIBLE")
		e:True(string.find(st.reason, "foo", 1, true) ~= nil)
	end)
	t:It("ungetestete Version = DEGRADED statt ACTIVE", function(e)
		local m = LMNT.Integrations.New({ persist = false })
		m:Register("v", { detect = found(2, "9.9"), testedVersions = { "1.0" } })
		m:StartAll()
		e:Equal(m:GetStatus("v").state, "DEGRADED")
	end)
	t:It("passende Version und Schnittstelle = ACTIVE, Nachweis 'interface'", function(e)
		local m = LMNT.Integrations.New({ persist = false })
		m:Register("ok", { detect = found(2, "1.0"), testedVersions = { "1.0" }, validate = function() return { { name = "a", ok = true } } end })
		m:StartAll()
		e:Equal(m:GetStatus("ok").state, "ACTIVE")
		e:Equal(m:GetStatus("ok").level, "interface")
	end)
	t:It("fehlende Abhängigkeit = MISSING_DEPENDENCY", function(e)
		local m = LMNT.Integrations.New({ persist = false })
		m:Register("kind", { detect = found(2), depends = { "gibtsnicht" } })
		m:StartAll()
		e:Equal(m:GetStatus("kind").state, "MISSING_DEPENDENCY")
	end)
	t:It("Fehler beim Aktivieren = FAILED, Registrierungen zurückgenommen", function(e)
		local m = LMNT.Integrations.New({ persist = false })
		m:Register("boom", { detect = found(2), init = function()
			hook.Add("Think", "LMNT.TestIntegrationBoom", function() end)
			error("absichtlich")
		end })
		m:StartAll()
		e:Equal(m:GetStatus("boom").state, "FAILED")
		e:True((hook.GetTable().Think or {})["LMNT.TestIntegrationBoom"] == nil, "Hook zurückgenommen")
	end)
	t:It("Deaktivieren bereinigt, Live-Sperre wird respektiert", function(e)
		local m = LMNT.Integrations.New({ persist = false })
		m:Register("live", { detect = found(2), init = function() hook.Add("Think", "LMNT.TestIntegrationLive", function() end) end })
		m:Register("fest", { detect = found(2), live = false })
		m:StartAll()
		e:True(m:Disable("live"))
		e:True((hook.GetTable().Think or {})["LMNT.TestIntegrationLive"] == nil, "Hook entfernt")
		local ok = m:Disable("fest")
		e:False(ok, "nicht live abschaltbar")
		e:True(m:GetStatus("fest").pendingRestart, "für Neustart vorgemerkt")
	end)
	t:It("Konflikte werden erkannt und nicht über die Ladereihenfolge gelöst", function(e)
		local m = LMNT.Integrations.New({ persist = false })
		m:Register("a", { detect = found(2) })
		m:Register("b", { detect = found(2), conflicts = { "a" } })
		m:StartAll()
		e:Equal(m:GetStatus("a").state, "ACTIVE")
		e:Equal(m:GetStatus("b").state, "INCOMPATIBLE")
		e:Equal(#m:Conflicts(), 1)
	end)
	t:It("Tests heben die Nachweisstufe nur bei Erfolg", function(e)
		local m = LMNT.Integrations.New({ persist = false })
		m:Register("t", { detect = found(2), tests = {
			{ name = "gut", run = function(x) x:True(true) end },
			{ name = "schlecht", run = function(x) x:True(false) end },
		} })
		m:StartAll()
		local passed, failed = m:RunTests("t")
		e:Equal(passed, 1)
		e:Equal(failed, 1)
		e:Equal(m:GetStatus("t").level, "partial")
	end)
	t:It("Laufender Server: TTT2-Integration aktiv und Grundtest grün", function(e)
		local st = LMNT.Integrations.GetStatus("ttt2")
		e:True(st ~= nil, "registriert")
		e:True(st.state == "ACTIVE" or st.state == "DEGRADED", "Zustand " .. tostring(st.state) .. " " .. tostring(st.reason))
		local _, failed, messages = LMNT.Integrations.RunTests("ttt2")
		e:Equal(failed, 0, table.concat(messages, "; "))
	end)
end)
