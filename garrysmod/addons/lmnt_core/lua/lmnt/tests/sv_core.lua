-- LMNT Unit-Tests: Core, Util, Admin-Parser, Datenbank
local T = LMNT.Test

T.Describe("Core.Version", function(t)
	t:It("vergleicht SemVer korrekt", function(e)
		e:Equal(LMNT.CompareVersions("1.1.0", "1.1.0"), 0)
		e:Equal(LMNT.CompareVersions("1.2.0", "1.10.0"), -1, "numerisch statt alphabetisch")
		e:Equal(LMNT.CompareVersions("2.0.0", "1.99.99"), 1)
	end)
	t:It("RequireVersion wirft bei zu neuer Anforderung", function(e)
		e:Error(function() LMNT.RequireVersion("99.0.0", "Test") end)
		e:NoError(function() LMNT.RequireVersion("1.0.0", "Test") end)
	end)
	t:It("Phase ist nach dem Start 'ready'", function(e)
		e:Equal(LMNT.GetPhase(), "ready")
	end)
end)

T.Describe("Util.ParseTime", function(t)
	t:It("liest Einheiten", function(e)
		e:Equal(LMNT.ParseTime("30m"), 30)
		e:Equal(LMNT.ParseTime("2h"), 120)
		e:Equal(LMNT.ParseTime("1d12h"), 2160)
		e:Equal(LMNT.ParseTime("1w"), 10080)
		e:Equal(LMNT.ParseTime("90"), 90)
	end)
	t:It("permanent und Fehler", function(e)
		e:Equal(LMNT.ParseTime("0"), 0)
		e:Equal(LMNT.ParseTime("perm"), 0)
		e:Equal(LMNT.ParseTime("5x"), nil, "unbekannte Einheit")
		e:Equal(LMNT.ParseTime("abc"), nil)
	end)
	t:It("FormatMinutes", function(e)
		e:Equal(LMNT.FormatMinutes(0), "permanent")
		e:Equal(LMNT.FormatMinutes(1501), "1T 1Std 1Min")
	end)
end)

T.Describe("Admin.Tokenize", function(t)
	t:It("trennt an Leerzeichen und respektiert Anführungszeichen", function(e)
		local tok = LMNT.Admin.Tokenize('ban "Max Mustermann" 1d Grund hier')
		e:Equal(#tok, 5)
		e:Equal(tok[2], "Max Mustermann")
		e:Equal(tok[5], "hier")
	end)
	t:It("leere Eingabe", function(e)
		e:Equal(#LMNT.Admin.Tokenize("   "), 0)
	end)
end)

T.Describe("Admin.Rechte", function(t)
	t:It("Vererbung und Wildcard", function(e)
		e:True(LMNT.RankHasPerm("moderator", "kick"), "moderator erbt kick von supporter")
		e:False(LMNT.RankHasPerm("supporter", "unban"))
		e:True(LMNT.RankHasPerm("superadmin", "irgendwas"), "superadmin hat *")
		e:False(LMNT.RankHasPerm("user", "kick"))
		e:True(LMNT.RankHasPerm("user", nil), "nil-Recht = für alle")
	end)
	t:It("unbekanntes Recht ist verweigert (deny by default)", function(e)
		e:False(LMNT.RankHasPerm("admin", "gibt.es.nicht"))
		e:False(LMNT.RankHasPerm("unbekannter_rang", "kick"))
	end)
end)

T.Describe("DB", function(t)
	t:It("Parameterbindung escaped Strings (SQL-Injection)", function(e)
		LMNT.DB.Query("CREATE TABLE IF NOT EXISTS lmnt_test_tmp (v TEXT)")
		LMNT.DB.Query("DELETE FROM lmnt_test_tmp")
		LMNT.DB.Query("INSERT INTO lmnt_test_tmp (v) VALUES (?)", "x'); DROP TABLE lmnt_test_tmp; --")
		e:Equal(LMNT.DB.Value("SELECT COUNT(*) FROM lmnt_test_tmp"), "1")
		e:Equal(LMNT.DB.Value("SELECT v FROM lmnt_test_tmp"), "x'); DROP TABLE lmnt_test_tmp; --")
	end)
	t:It("Transaktion wird bei Fehler zurückgerollt", function(e)
		LMNT.DB.Query("DELETE FROM lmnt_test_tmp")
		local ok = LMNT.DB.Transaction(function()
			LMNT.DB.Query("INSERT INTO lmnt_test_tmp (v) VALUES (?)", "a")
			error("absichtlich")
		end)
		e:False(ok)
		e:Equal(LMNT.DB.Value("SELECT COUNT(*) FROM lmnt_test_tmp"), "0", "nichts geschrieben")
	end)
	t:It("EnsureColumn ist idempotent", function(e)
		LMNT.DB.EnsureColumn("lmnt_test_tmp", "extra", "INTEGER DEFAULT 0")
		e:True(LMNT.DB.ColumnExists("lmnt_test_tmp", "extra"))
		e:False(LMNT.DB.EnsureColumn("lmnt_test_tmp", "extra", "INTEGER DEFAULT 0"), "zweiter Aufruf ändert nichts")
		LMNT.DB.Query("DROP TABLE lmnt_test_tmp")
	end)
end)
