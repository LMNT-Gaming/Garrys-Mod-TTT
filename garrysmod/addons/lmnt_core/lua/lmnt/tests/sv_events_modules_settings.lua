-- LMNT Unit-Tests: Events, Settings, Module (mit eigenen Instanzen, ohne den laufenden Server zu verändern)
local T = LMNT.Test

T.Describe("Events", function(t)
	t:It("Fehler in einem Listener stoppt die anderen nicht", function(e)
		local bus = LMNT.Events.New()
		local ran = 0
		bus:On("x", "a", function() error("kaputt") end)
		bus:On("x", "b", function() ran = ran + 1 end)
		bus:Emit("x")
		e:Equal(ran, 1)
		e:Equal(bus:Stats().x.errors, 1)
	end)
	t:It("gleiche id ersetzt (keine Doppelregistrierung)", function(e)
		local bus = LMNT.Events.New()
		local ran = 0
		bus:On("x", "a", function() ran = ran + 1 end)
		bus:On("x", "a", function() ran = ran + 10 end)
		bus:Emit("x")
		e:Equal(ran, 10)
		e:Equal(bus:ListenerCount("x"), 1)
	end)
	t:It("Ask: Priorität, erster Wert gewinnt, Rest läuft nicht", function(e)
		local bus = LMNT.Events.New()
		bus:Define("q", { decision = true })
		local lowRan = false
		bus:On("q", "low", function() lowRan = true return "low" end, { priority = 0 })
		bus:On("q", "high", function() return "high" end, { priority = 10 })
		local result, by = bus:Ask("q")
		e:Equal(result, "high")
		e:Equal(by, "high")
		e:False(lowRan, "niedrige Priorität darf nicht mehr laufen")
	end)
	t:It("Ask auf Beobachter-Event ist ein Fehler", function(e)
		local bus = LMNT.Events.New()
		bus:Define("obs", { decision = false })
		e:Error(function() bus:Ask("obs") end)
	end)
	t:It("RemoveOwner entfernt nur Listener des Eigentümers", function(e)
		local bus = LMNT.Events.New()
		bus:On("x", "a", function() end, { owner = "m1" })
		bus:On("x", "b", function() end, { owner = "m2" })
		e:Equal(bus:RemoveOwner("m1"), 1)
		e:Equal(bus:ListenerCount("x"), 1)
	end)
end)

T.Describe("Settings.Validate", function(t)
	local V = LMNT.Settings.Validate
	t:It("Zahlen mit Grenzen", function(e)
		local def = { type = "number", min = 0, max = 1 }
		e:True(V(def, 0.5))
		e:False(V(def, 2))
		e:False(V(def, "abc"))
		local ok, n = V(def, "0.25")
		e:True(ok)
		e:Equal(n, 0.25, "String wird normalisiert")
	end)
	t:It("int lehnt Kommazahlen ab", function(e)
		e:False(V({ type = "int" }, 1.5))
		e:True(V({ type = "int" }, "3"))
	end)
	t:It("bool akzeptiert an/aus und 1/0", function(e)
		local _, a = V({ type = "bool" }, "an")
		local _, b = V({ type = "bool" }, "0")
		e:Equal(a, true)
		e:Equal(b, false)
		e:False(V({ type = "bool" }, "vielleicht"))
	end)
	t:It("enum nur erlaubte Werte", function(e)
		local def = { type = "enum", choices = { "rot", "blau" } }
		e:True(V(def, "rot"))
		e:False(V(def, "grün"))
	end)
	t:It("Define lehnt ungültigen Standardwert ab", function(e)
		e:Error(function() LMNT.Settings.Define("test.ungueltig", { type = "int", default = 5, max = 3 }) end)
	end)
end)

T.Describe("Settings.Persistenz", function(t)
	t:It("Set -> Get -> Reset, ungültige Werte werden abgelehnt", function(e)
		local key = "test.lmnt.tmp"
		LMNT.Settings.Define(key, { type = "int", default = 3, min = 1, max = 10, category = "Test" })
		e:Equal(LMNT.Settings.Get(key), 3)
		e:True(LMNT.Settings.Set(key, 7))
		e:Equal(LMNT.Settings.Get(key), 7)
		e:Equal(LMNT.DB.Value("SELECT value FROM lmnt_config WHERE key = ?", key), "7", "gespeichert")
		e:False(LMNT.Settings.Set(key, 99), "außerhalb des Bereichs")
		e:Equal(LMNT.Settings.Get(key), 7, "Wert unverändert")
		LMNT.Settings.Reset(key)
		e:Equal(LMNT.Settings.Get(key), 3)
		e:Equal(LMNT.DB.Value("SELECT COUNT(*) FROM lmnt_config WHERE key = ?", key), "0", "aus DB entfernt")
		LMNT.Settings._defs[key] = nil
		LMNT.Settings._values[key] = nil
	end)
end)

T.Describe("Module", function(t)
	t:It("Startreihenfolge nach Abhängigkeiten, fehlende Abhängigkeit = blocked", function(e)
		local reg = LMNT.Modules.New({ persist = false })
		local order = {}
		reg:Register({ id = "b", depends = { "a" }, init = function() order[#order + 1] = "b" end })
		reg:Register({ id = "a", init = function() order[#order + 1] = "a" end })
		reg:Register({ id = "c", depends = { "fehlt" } })
		reg:StartAll()
		e:Equal(table.concat(order, ","), "a,b")
		e:Equal(reg:Get("c").state, "blocked")
	end)
	t:It("Zyklen werden erkannt", function(e)
		local reg = LMNT.Modules.New({ persist = false })
		reg:Register({ id = "x", depends = { "y" } })
		reg:Register({ id = "y", depends = { "x" } })
		reg:StartAll()
		e:Equal(reg:Get("x").state, "failed")
		e:Equal(reg:Get("y").state, "failed")
	end)
	t:It("Deaktivieren entfernt Hooks, Timer, Events und kaskadiert", function(e)
		local reg = LMNT.Modules.New({ persist = false })
		reg:Register({ id = "t.base", init = function()
			hook.Add("Think", "LMNT.TestHook", function() end)
			timer.Create("LMNT.TestTimer", 60, 0, function() end)
			LMNT.Events.On("lmnt.test.event", "LMNT.TestListener", function() end)
		end })
		reg:Register({ id = "t.child", depends = { "t.base" } })
		reg:StartAll()
		e:True((hook.GetTable().Think or {})["LMNT.TestHook"] ~= nil, "Hook registriert")
		e:True(timer.Exists("LMNT.TestTimer"), "Timer registriert")
		e:Equal(LMNT.Events.ListenerCount("lmnt.test.event"), 1)

		reg:Disable("t.base")
		e:True((hook.GetTable().Think or {})["LMNT.TestHook"] == nil, "Hook entfernt")
		e:False(timer.Exists("LMNT.TestTimer"), "Timer entfernt")
		e:Equal(LMNT.Events.ListenerCount("lmnt.test.event"), 0, "Listener entfernt")
		e:Equal(reg:Get("t.child").state, "blocked", "abhängiges Modul kontrolliert gestoppt")

		reg:Enable("t.base")
		e:Equal(reg:Get("t.child").state, "enabled", "abhängiges Modul wieder gestartet")
		reg:Disable("t.base")
	end)
	t:It("Fehler beim Start nimmt alle Registrierungen zurück", function(e)
		local reg = LMNT.Modules.New({ persist = false })
		reg:Register({ id = "kaputt", init = function()
			hook.Add("Think", "LMNT.TestBroken", function() end)
			error("absichtlich")
		end })
		reg:StartAll()
		e:Equal(reg:Get("kaputt").state, "failed")
		e:True((hook.GetTable().Think or {})["LMNT.TestBroken"] == nil, "Hook zurückgenommen")
	end)
	t:It("Admin-Befehle eines Moduls verschwinden beim Deaktivieren", function(e)
		local reg = LMNT.Modules.New({ persist = false })
		reg:Register({ id = "cmd", init = function()
			LMNT.Admin.AddCommand("lmnttestcmd", { aliases = { "lmnttestalias" }, run = function() end })
		end })
		reg:StartAll()
		e:True(LMNT.Admin.GetCommand("lmnttestalias") ~= nil)
		reg:Disable("cmd")
		e:True(LMNT.Admin.GetCommand("lmnttestcmd") == nil)
		e:True(LMNT.Admin.GetCommand("lmnttestalias") == nil, "Alias entfernt")
	end)
	t:It("Konflikte blockieren", function(e)
		local reg = LMNT.Modules.New({ persist = false })
		reg:Register({ id = "p" })
		reg:Register({ id = "q", conflicts = { "p" } })
		reg:StartAll()
		e:Equal(reg:Get("p").state, "enabled")
		e:Equal(reg:Get("q").state, "blocked")
	end)
	t:It("Laufendes System: alle TTT-Module aktiv", function(e)
		for _, m in ipairs(LMNT.Modules.Status()) do
			e:Equal(m.state, "enabled", m.id)
		end
	end)
end)
